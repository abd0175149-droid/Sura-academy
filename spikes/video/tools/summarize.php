<?php

declare(strict_types=1);

/*
 * WP-0.4 results from the spike's logs (token-server/var, git-ignored) into name-free tables
 * (spikes/video/results/, committed):
 *   join-times.csv   automatic trials per provider × platform × device × network (NFR < 10 s at p95)
 *   summary.md       the same table, attendance minutes from webhooks, 1.5 Mbit/s stats, monthly cost
 *
 *   php spikes/video/tools/summarize.php [--down-mbps 1.0] [--recorded-share 0.5]
 * --down-mbps overrides the downstream bitrate measured from the bots' receiver stats.
 */

use Spike\Video\AttendanceProbe;
use Spike\Video\Results;

$here = dirname(__DIR__);
require $here.'/token-server/src/autoload.php';
$var = $here.'/token-server/var';
$out = $here.'/results';
@mkdir($out, 0755, true);

$opts = getopt('', ['down-mbps:', 'recorded-share:']);
$jsonl = static function (string $file): array {
    if (! is_file($file)) {
        return [];
    }

    return array_values(array_filter(array_map(
        static fn (string $l): mixed => json_decode($l, true),
        file($file, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [],
    ), 'is_array'));
};

// 1. Join times -------------------------------------------------------------------------------
$summary = Results::joinSummary($jsonl($var.'/metrics.jsonl'));
$csv = fopen($out.'/join-times.csv', 'w');
fputcsv($csv, ['provider', 'platform', 'device', 'network', 'n', 'ok', 'p50_s', 'p95_s', 'max_s', 'meets_nfr'], escape: '');
foreach ($summary as $row) {
    fputcsv($csv, array_map(static fn (mixed $v): string => is_bool($v) ? ($v ? 'yes' : 'no') : (string) ($v ?? ''), $row), escape: '');
}
fclose($csv);

$md = ["# WP-0.4 results (generated by tools/summarize.php, ".gmdate('Y-m-d H:i').' UTC)', '', '## Join time: tap → first remote video (automatic trials)', ''];
$md[] = '| Provider | Platform | Device | Network | Trials | OK | p50 (s) | p95 (s) | Max (s) | p95 < 10 s |';
$md[] = '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |';
foreach ($summary as $r) {
    $md[] = sprintf('| %s | %s | %s | %s | %d | %d | %s | %s | %s | %s |', $r['provider'], $r['platform'], $r['device'], $r['network'], $r['n'], $r['ok'], $r['p50_s'] ?? '—', $r['p95_s'] ?? '—', $r['max_s'] ?? '—', $r['meets_nfr'] ? 'yes' : '**no**');
}
if ($summary === []) {
    $md[] = '| — | — | — | — | 0 | 0 | — | — | — | — |';
}

// 2. Attendance from webhooks ------------------------------------------------------------------
$events = $jsonl($var.'/events.jsonl');
$md[] = '';
$md[] = '## Attendance minutes from provider webhooks (CLS-09)';
$md[] = '';
$md[] = '| Provider | Room | Identity | Minutes | Join/leave events |';
$md[] = '| --- | --- | --- | --- | --- |';
foreach (['livekit', 'zoom'] as $provider) {
    $mine = array_values(array_filter($events, static fn (array $e): bool => ($e['provider'] ?? null) === $provider));
    $rooms = array_unique(array_filter(array_column($mine, 'room')));
    foreach ($rooms as $room) {
        $last = max(array_column(array_filter($mine, static fn (array $e): bool => ($e['room'] ?? null) === $room), 'at'));
        foreach (AttendanceProbe::minutes($mine, $room, $last) as $who => $minutes) {
            $count = count(array_filter($mine, static fn (array $e): bool => ($e['room'] ?? null) === $room && ($e['identity'] ?? null) === $who));
            $md[] = "| {$provider} | {$room} | {$who} | {$minutes} | {$count} |";
        }
    }
}

// 3. Receiver stats (normal bot and 1.5 Mbit/s bot) -------------------------------------------
$md[] = '';
$md[] = '## Receiver stats per bot (CLS-14, downstream bitrate for the cost model)';
$md[] = '';
$md[] = '| Bot | Samples | Audio-only share | Median received height (px) | Median fps | Downstream video (Mbit/s) |';
$md[] = '| --- | --- | --- | --- | --- | --- |';
$measuredMbps = [];
foreach (glob($var.'/stats-bot-*.jsonl') ?: [] as $file) {
    $lines = $jsonl($file);
    if (count($lines) < 2) {
        continue;
    }
    $heights = [];
    $fps = [];
    $audioOnly = 0;
    foreach ($lines as $l) {
        $audioOnly += ($l['audio_only'] ?? false) ? 1 : 0;
        foreach ($l['remote_video'] ?? [] as $v) {
            if (($v['h'] ?? 0) > 0) {
                $heights[] = $v['h'];
            }
            if (($v['fps'] ?? 0) > 0) {
                $fps[] = $v['fps'];
            }
        }
    }
    $bytes = static fn (array $l): int => (int) array_sum(array_map(static fn (array $v): int => (int) ($v['bytes'] ?? 0), $l['remote_video'] ?? []));
    $seconds = strtotime(end($lines)['t']) - strtotime($lines[0]['t']);
    $mbps = $seconds > 0 ? max(0, $bytes(end($lines)) - $bytes($lines[0])) * 8 / $seconds / 1e6 : 0.0;
    $median = static function (array $xs): string {
        sort($xs);

        return $xs === [] ? '—' : (string) $xs[intdiv(count($xs), 2)];
    };
    $name = basename($file, '.jsonl');
    if (! str_ends_with($name, '-2')) {
        $measuredMbps[] = $mbps;
    }
    $md[] = sprintf('| %s | %d | %d%% | %s | %s | %.2f |', $name, count($lines), (int) round(100 * $audioOnly / count($lines)), $median($heights), $median($fps), $mbps);
}

// 4. Monthly cost ------------------------------------------------------------------------------
$down = isset($opts['down-mbps']) ? (float) $opts['down-mbps'] : ($measuredMbps === [] ? 1.0 : max($measuredMbps));
$load = Results::load(classes: 100, participants: 4, minutes: 75, sessionsPerMonth: 8);
$p = Results::PRICES;
$md[] = '';
$md[] = sprintf('## Monthly cost: 100 classes × 4 participants × 75 min × 8 sessions = %s participant-minutes (%s room-minutes)', number_format($load['participant_minutes']), number_format($load['room_minutes']));
$md[] = '';
$md[] = sprintf('Prices checked %s: LiveKit %s · Zoom %s. Downstream per participant: %.2f Mbit/s (%s).', $p['checked'], $p['livekit']['source'], $p['zoom']['source'], $down, isset($opts['down-mbps']) ? 'given' : ($measuredMbps === [] ? 'assumed, no stats yet' : 'measured'));
$md[] = '';
$md[] = '| Share of classes recorded | Zoom (USD) | LiveKit Ship (USD) | LiveKit Scale, EU pinning possible (USD) |';
$md[] = '| --- | --- | --- | --- |';
$shares = isset($opts['recorded-share']) ? [(float) $opts['recorded-share']] : [0.0, 0.5, 1.0];
foreach ($shares as $share) {
    $z = Results::zoomCost($load, $share);
    $ship = Results::liveKitCost($load, $share, $down, 'ship');
    $scale = Results::liveKitCost($load, $share, $down, 'scale');
    $md[] = sprintf('| %d%% | %s | %s | %s |', (int) ($share * 100), number_format($z['total_usd'], 2), number_format($ship['total_usd'], 2), number_format($scale['total_usd'], 2));
}
$md[] = '';
$md[] = 'LiveKit Ship allows 100 concurrent egress (recordings); at 100 concurrent classes all recorded, that is the limit. Zoom recording storage is ~0 because D-16 deletes within 24 h.';

file_put_contents($out.'/summary.md', implode("\n", $md)."\n");
echo implode("\n", $md)."\n";
