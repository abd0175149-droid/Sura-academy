<?php

declare(strict_types=1);

/*
 * WP-0.5: turn server/var/*.jsonl into committed, name-free results.
 *
 *   php spikes/flutter-web/tools/summarize.php
 *
 * Writes results/load-times.csv (one row per load) and results/summary.md (p50/p95 per device,
 * network, variant and cold/warm, checked against the D-22 default targets), plus what the browser
 * asked for in font fallback and what the CSP reported.
 */

$spike = dirname(__DIR__);
$var = $spike.'/server/var';
$results = $spike.'/results';

/** @return list<array<string, mixed>> */
function lines(string $file): array
{
    if (! is_file($file)) {
        return [];
    }

    return array_values(array_filter(array_map(
        static fn (string $l): mixed => json_decode($l, true),
        file($file, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [],
    ), 'is_array'));
}

function pct(array $values, float $p): ?int
{
    if ($values === []) {
        return null;
    }
    sort($values);

    return (int) round($values[max(0, (int) ceil($p * count($values)) - 1)]);
}

function fmt(?int $ms): string
{
    return $ms === null ? '—' : number_format($ms / 1000, 2);
}

// D-22 default targets (decisions.md): splash LCP ≤ 2.5 s; interactive ≤ 5 s first load, ≤ 2 s later loads.
const SPLASH = 2500;
const FIRST = 5000;
const LATER = 2000;

$metrics = lines($var.'/metrics.jsonl');
$csv = fopen($results.'/load-times.csv', 'w');
$cols = ['device', 'network', 'variant', 'phase', 'wasm', 'threads', 'isolated', 'sw', 'semantics', 'fcp', 'lcp', 'entrypoint', 'engine', 'first_frame', 'interactive', 'transfer_kb', 'browser'];
fputcsv($csv, $cols, escape: '');
$groups = [];
$hidden = [];
foreach ($metrics as $m) {
    $marks = $m['marks'] ?? [];
    $ua = (string) ($m['ua'] ?? '');
    $browser = match (true) {
        str_contains($ua, 'CriOS') => 'chrome-ios',
        str_contains($ua, 'Edg/') => 'edge',
        str_contains($ua, 'Chrome/') => 'chrome '.(preg_match('/Chrome\/(\d+)/', $ua, $v) ? $v[1] : ''),
        str_contains($ua, 'Safari/') => 'safari '.(preg_match('/Version\/([\d.]+)/', $ua, $v) ? $v[1] : ''),
        str_contains($ua, 'Firefox/') => 'firefox',
        default => 'other',
    };
    $row = [
        $m['device'], $m['network'], $m['variant'], $m['phase'], json_encode($m['wasm'] ?? null), $m['threads'] ?? '',
        json_encode($m['isolated'] ?? null), $m['sw'] ?? '', json_encode($m['semantics'] ?? null),
        $marks['fcp'] ?? '', $marks['lcp'] ?? '', $marks['entrypoint'] ?? '', $marks['engine'] ?? '', $marks['first-frame'] ?? '',
        $marks['interactive'] ?? '', $m['transfer_kb'] ?? '', trim($browser),
    ];
    fputcsv($csv, $row, escape: '');
    if (($m['phase'] ?? '') === 'manual') {
        continue;
    }
    // A load with no first paint was never on screen (screen locked, background tab, prerender,
    // link-preview browser): it measures nothing a user would see. Counted, not summarized.
    if (! isset($marks['fcp']) && ! isset($marks['lcp'])) {
        $hidden[] = $m['device'].' '.$m['variant'].' '.$m['phase'].' ('.trim($browser).')';
        continue;
    }
    $variant = $m['variant'].(($m['semantics'] ?? true) === false ? ' sem-off' : '');
    $key = implode(' | ', [$m['device'], $m['network'], $variant, $m['phase']]);
    $groups[$key]['splash'][] = $marks['lcp'] ?? $marks['fcp'] ?? null;
    $groups[$key]['interactive'][] = $marks['interactive'] ?? null;
    $groups[$key]['transfer'][] = $m['transfer_kb'] ?? null;
    $groups[$key]['runs_as'] = ($m['wasm'] ?? false) ? 'WASM '.($m['threads'] ?? '') : 'JS';
}
fclose($csv);
ksort($groups);

$out = ['# WP-0.5 results', '', 'Generated by `tools/summarize.php` from the spike server\'s metrics. Times in seconds from navigation start (p50 / p95). Targets are the D-22 defaults: splash ≤ 2.50 s; interactive ≤ 5.00 s on the first load (cold) and ≤ 2.00 s on later loads (warm).', ''];
$out[] = '| Device | Network | Variant | Load | Runs as | n | Splash p50 / p95 | Interactive p50 / p95 | Downloaded KB (p50) | Meets D-22 at p95 |';
$out[] = '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |';
foreach ($groups as $key => $g) {
    [$device, $network, $variant, $phase] = explode(' | ', $key);
    $splash = array_values(array_filter($g['splash'], 'is_numeric'));
    $inter = array_values(array_filter($g['interactive'], 'is_numeric'));
    $limit = $phase === 'warm' ? LATER : FIRST;
    $ok = $splash !== [] && $inter !== [] && pct($splash, .95) <= SPLASH && pct($inter, .95) <= $limit;
    $out[] = sprintf('| %s | %s | `%s` | %s | %s | %d | %s / %s | %s / %s | %s | %s |',
        $device, $network, $variant, $phase, $g['runs_as'], count($inter),
        fmt(pct($splash, .5)), fmt(pct($splash, .95)), fmt(pct($inter, .5)), fmt(pct($inter, .95)),
        pct(array_values(array_filter($g['transfer'], 'is_numeric')), .5) ?? '—', $ok ? 'yes' : 'no');
}

if ($hidden !== []) {
    $out[] = '';
    $out[] = 'Left out: '.count($hidden).' loads without a first paint (page not on screen): '.implode('; ', array_map(static fn ($k, $v) => "{$k} ×{$v}", array_keys(array_count_values($hidden)), array_count_values($hidden))).'.';
}
$out[] = '';
$out[] = 'Device loads went through a Cloudflare quick tunnel to this machine, which served them gzip (iPad ~4,435 KB, Android ~3,250 KB per cold load), not brotli as a CDN would (see the size table).';

// Bundle sizes: the files each engine path downloads on a cold load (sizes.csv, brotli as served).
$sizes = [];
if (is_file($results.'/sizes.csv')) {
    foreach (array_slice(file($results.'/sizes.csv', FILE_IGNORE_NEW_LINES) ?: [], 1) as $line) {
        [$build, $file, $raw, $gz, $br] = str_getcsv($line, escape: '');
        $sizes[$build][$file] = ['raw' => (int) $raw, 'gz' => (int) $gz, 'br' => (int) $br];
    }
}
// Flutter web downloads every family in FontManifest.json at start-up, plus the Roboto it bundles
// as its default fallback when built with --no-web-resources-cdn.
$fonts = [
    'assets/FontManifest.json', 'assets/AssetManifest.bin.json',
    'assets/assets/fonts/IBMPlexSansArabic-Regular.ttf', 'assets/assets/fonts/IBMPlexSansArabic-Medium.ttf',
    'assets/assets/fonts/IBMPlexSansArabic-SemiBold.ttf', 'assets/assets/fonts/IBMPlexSansArabic-Bold.ttf',
    'assets/assets/fonts/NotoNaskhArabic-Regular.ttf', 'assets/assets/fonts/NotoNaskhArabic-SemiBold.ttf',
    'assets/fonts/MaterialIcons-Regular.otf', 'assets/fonts/fallback/Roboto-Regular.ttf',
];
$paths = [
    'Chrome, WebAssembly (skwasm)' => ['web-wasm', ['main.dart.wasm', 'main.dart.mjs', 'flutter_bootstrap.js', 'canvaskit/skwasm.js', 'canvaskit/skwasm.wasm', ...$fonts]],
    'Chrome, JavaScript (CanvasKit, Chromium variant)' => ['web-js', ['main.dart.js', 'flutter_bootstrap.js', 'canvaskit/chromium/canvaskit.js', 'canvaskit/chromium/canvaskit.wasm', ...$fonts]],
    'Safari / Firefox, JavaScript (CanvasKit, full)' => ['web-js', ['main.dart.js', 'flutter_bootstrap.js', 'canvaskit/canvaskit.js', 'canvaskit/canvaskit.wasm', ...$fonts]],
];
$out[] = '';
$out[] = '## What a cold load downloads (from `sizes.csv`)';
$out[] = '';
$out[] = '| Engine path | Files | Raw KB | Gzip KB | Brotli KB (as served) |';
$out[] = '| --- | --- | --- | --- | --- |';
foreach ($paths as $label => [$build, $files]) {
    $sum = ['raw' => 0, 'gz' => 0, 'br' => 0];
    $n = 0;
    foreach ($files as $f) {
        if (isset($sizes[$build][$f])) {
            $n++;
            foreach ($sum as $k => $_) {
                $sum[$k] += $sizes[$build][$f][$k] ?: $sizes[$build][$f]['raw'];
            }
        }
    }
    $out[] = sprintf('| %s | %d | %s | %s | %s |', $label, $n, number_format($sum['raw'] / 1024), number_format($sum['gz'] / 1024), number_format($sum['br'] / 1024));
}
$fontBr = array_sum(array_map(static fn (string $f): int => $sizes['web-js'][$f]['br'] ?? 0, $fonts));
$out[] = '';
$out[] = 'Of which fonts and manifests: '.number_format($fontBr / 1024).' KB brotli (4 IBM Plex Sans Arabic weights, 2 Noto Naskh Arabic weights, Material Icons, Roboto).';
$out[] = '';
$out[] = 'Largest single files (brotli): '.implode(', ', array_map(
    static fn (array $x): string => "`{$x[0]}` ".number_format($x[1] / 1024).' KB',
    (static function () use ($sizes): array {
        $all = [];
        foreach ($sizes['web-wasm'] ?? [] as $f => $s) {
            if ($s['br'] > 0 && ! str_ends_with($f, '.symbols')) {
                $all[] = [$f, $s['br']];
            }
        }
        usort($all, static fn ($a, $b) => $b[1] <=> $a[1]);

        return array_slice($all, 0, 6);
    })(),
)).'.';

$fallback = lines($var.'/fallback-fonts.jsonl');
$families = array_count_values(array_map(static fn (array $f): string => explode('/', (string) $f['path'])[0], $fallback));
$out[] = '';
$out[] = '## Font fallback requests (all to our origin, answered 404)';
$out[] = '';
$out[] = $families === [] ? 'None.' : implode(', ', array_map(static fn ($k, $v) => "`{$k}` ×{$v}", array_keys($families), $families)).'.';

$csp = lines($var.'/csp.jsonl');
$kinds = array_count_values(array_map(static fn (array $c): string => $c['disposition'].' · '.$c['directive'].' · '.preg_replace('#^(https?://[^/]+).*#', '$1', (string) $c['blocked']), $csp));
$out[] = '';
$out[] = '## CSP reports';
$out[] = '';
$out[] = $kinds === [] ? 'None.' : implode(PHP_EOL, array_map(static fn ($k, $v) => "- {$k} ×{$v}", array_keys($kinds), $kinds));

$feedback = lines($var.'/feedback.jsonl');
if ($feedback !== []) {
    $out[] = '';
    $out[] = '## Owner checklist answers';
    $out[] = '';
    foreach ($feedback as $f) {
        $out[] = '- '.$f['device'].' (`'.($f['variant'] ?? '').'`): '.implode(', ', array_map(static fn ($q, $a) => "{$q} {$a}", array_keys($f['answers']), $f['answers']));
    }
}

file_put_contents($results.'/summary.md', implode(PHP_EOL, $out).PHP_EOL);
echo 'wrote results/load-times.csv ('.count($metrics).' loads) and results/summary.md'.PHP_EOL;
